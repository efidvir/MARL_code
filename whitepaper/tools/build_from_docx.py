#!/usr/bin/env python3
"""Regenerate sections/*.tex and figures/ from the source .docx.

Usage: python3 tools/build_from_docx.py path/to/T23_D24.docx
Requires pandoc >= 3.1 on PATH. Run from the whitepaper directory.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

MARK_FILL = "72B2CF"   # cell shading that marks a requirement-to-KPI link


def mark_shaded_cells(src, dst):
    """The KPI mapping matrices mark a link by shading an empty cell, which pandoc
    drops; write a copy of the docx in which those cells carry the text KPIMARK."""
    def fill(m):
        cell = m.group(0)
        if f'w:fill="{MARK_FILL}"' in cell and not re.search(r"<w:t[ >]", cell):
            cell = cell.replace("<w:r/>", "<w:r><w:t>KPIMARK</w:t></w:r>", 1)
        return cell

    with zipfile.ZipFile(src) as zin, zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename == "word/document.xml":
                xml = data.decode("utf-8")
                xml = re.sub(r"<w:tbl>.*?</w:tbl>",
                             lambda t: re.sub(r"<w:tc>.*?</w:tc>", fill, t.group(0), flags=re.S)
                             if "KPI\\Requirement" in re.sub(r"<[^>]+>", "", t.group(0)) else t.group(0),
                             xml, flags=re.S)
                data = xml.encode("utf-8")
            zout.writestr(item, data)

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILTER = os.path.join(HERE, "tools", "whitepaper.lua")

FILES = [
    "01-introduction", "02-lineage-and-state-of-the-art", "03-the-ai-native-agent-framework",
    "04-the-monitoring-system", "05-the-analytics-engine", "06-the-decision-engine",
    "07-the-actuator", "08-interconnection", "09-lifecycle",
    "10-conflict-resolution-and-governance", "11-integration",
    "12-key-performance-indicators-and-value-indicators",
    "annex-a-json-schemas", "annex-b-type-catalog",
]


def main(docx):
    tmp = tempfile.mkdtemp()
    body = os.path.join(tmp, "body.tex")
    marked = os.path.join(tmp, "marked.docx")
    mark_shaded_cells(docx, marked)
    subprocess.run(["pandoc", marked, "-t", "latex", "--top-level-division=section",
                    "--extract-media", tmp, "--lua-filter", FILTER, "-o", body], check=True)
    tex = open(body, encoding="utf-8").read()

    # figures/ directory with stable names
    figdir = os.path.join(HERE, "figures")
    os.makedirs(figdir, exist_ok=True)
    for name in os.listdir(os.path.join(tmp, "media")):
        shutil.copy(os.path.join(tmp, "media", name), os.path.join(figdir, name))
    tex = re.sub(r"\{(?:[^{}]*/)?media/(image\d+\.\w+)\}", r"{figures/\1}", tex)

    # let snake_case identifiers inside \texttt{} break after underscores
    tex = re.sub(r"\\texttt\{[^{}]*\}", lambda m: m.group(0).replace("\\_", "\\_\\allowbreak{}"), tex)

    # \appendix lives in main.tex
    tex = tex.replace("\\appendix\n", "")

    # split at each top-level section (pandoc wraps it in \hypertarget{..}{%)
    starts = [m.start() for m in re.finditer(r"^\\hypertarget\{[^}]*\}\{%\n\\section\{", tex, re.M)]
    if len(starts) != len(FILES):
        sys.exit(f"expected {len(FILES)} top-level sections, found {len(starts)}")
    os.makedirs(os.path.join(HERE, "sections"), exist_ok=True)
    for i, name in enumerate(FILES):
        chunk = tex[starts[i]:starts[i + 1] if i + 1 < len(starts) else len(tex)]
        with open(os.path.join(HERE, "sections", name + ".tex"), "w", encoding="utf-8") as f:
            f.write(f"%% {name}.tex -- generated by tools/build_from_docx.py; edit freely\n\n")
            f.write(chunk.rstrip() + "\n")
    shutil.rmtree(tmp)
    print(f"wrote {len(FILES)} section files and {len(os.listdir(figdir))} figures")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
