"""Build plan for the selected testbed, option A.

Derives, from the same analysis as the figures:
  * the kit on each of the eight site carts;
  * the V-band RF mesh: every TG path, the conducted loss that reproduces
    its geometry, the splitter losses and the programmable-attenuator
    setting in each state (before the event, at t0, after MARL recovery);
  * the microwave (IP-50) chains.

How the conducted bench emulates the radio layer
-------------------------------------------------
Over the air a 60 GHz path costs FSPL + O2 absorption and gains 24 dBi at
each end (MARL paper Table III).  Cabled, the antennas are bypassed, so the
loss that reproduces the same received level is FSPL + O2 - 48 dB.  A beam
pointed elsewhere costs the sidelobe discrimination, 15 dB per end (Table
III), so a candidate bridge sits 30 dB above its on-beam loss until both
ends steer: steering is a 30 dB step down on that path's attenuator.  The
event drives every path to CORE and HUB to the attenuator maximum (and the
PDUs switch those carts off).

Run:  python3 option_a_plan.py     -> out/option_A_plan.md
"""
import math
import os

from bom import counts, rf_mesh
from topologies import ROLE
from validate import analyze, dist, P_PLAN, tg_snr

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")

ANT_GAIN_TOTAL = 48.0      # 24 dBi per end (Table III)
SIDELOBE_PER_END = 15.0    # Table III
VPAD_DB = 20.0             # V-band fixed pad per sector port
JUMPER_DB = 3.0            # V-band jumpers per path (assumption; measure on the bench)
ATT_MAX = 95.0             # programmable attenuator range used as "cut"
MW_PAD_DB = 30.0           # microwave fixed pad, each end
MW_ATT_NOMINAL = 10.0      # microwave programmable attenuator at rest (head-room for fades)


def splitter_loss(k):
    """1:k splitter/combiner: power split plus ~1.5 dB excess; none if k = 1."""
    return 0.0 if k <= 1 else 10 * math.log10(k) + 1.5


def air_equivalent_loss(d):
    fspl = 20 * math.log10(d) + 20 * math.log10(60000) - 27.55
    return fspl + 0.015 * d - ANT_GAIN_TOTAL


def plan():
    r = analyze("A")
    cfg = r["cfg"]
    pos = r["pos"]
    mesh = rf_mesh(r)
    fan = mesh["ports"]
    bridges = {frozenset(b) for b in cfg["bridges"]}
    pre = {frozenset(e) for e in r["tg_all"]}
    dead = set(cfg["destroyed"])
    rows = []
    for a, b in mesh["links"]:
        e = frozenset((a, b))
        d = dist(pos[a], pos[b])
        pa, pb = r["end_sector"](a, b), r["end_sector"](b, a)
        target = air_equivalent_loss(d)
        fixed = 2 * VPAD_DB + splitter_loss(fan[pa]) + splitter_loss(fan[pb]) + JUMPER_DB
        on = target - fixed
        off = on + 2 * SIDELOBE_PER_END
        role = ("hub link" if "HUB" in e else "core spur" if "CORE" in e else
                "spare sector" if e in pre else "bridge (chosen)" if e in bridges else "bridge candidate")
        before = on if e in pre else off
        at_t0 = ATT_MAX if e & dead else before
        after = ATT_MAX if e & dead else (on if (e in pre or e in bridges) else off)
        rows.append(dict(a=a, b=b, role=role, d=d, target=target, split_a=splitter_loss(fan[pa]),
                         split_b=splitter_loss(fan[pb]), fixed=fixed, on=on, off=off, before=before,
                         at_t0=at_t0, after=after, snr=tg_snr(d), port_a=pa, port_b=pb))
    order = {"hub link": 0, "core spur": 1, "spare sector": 2, "bridge (chosen)": 3, "bridge candidate": 4}
    rows.sort(key=lambda x: (order[x["role"]], x["a"], x["b"]))

    mw = []
    for a, b in cfg["mw"]:
        mw.append(dict(a=a, b=b, d=dist(pos[a], pos[b]), pads=2 * MW_PAD_DB, att=MW_ATT_NOMINAL,
                       cut=a in dead or b in dead))

    endpoints = {x for _, s, t in cfg["flows"] for x in (s, t)} | \
        {x for s, t in cfg.get("service", []) for x in (s, t)}
    ports_per_site = {}
    for (site, sec), k in fan.items():
        ports_per_site.setdefault(site, []).append((sec, k))
    kit = []
    for s in cfg["sites"]:
        kit.append(dict(site=s, role=ROLE[s].split("\n")[0], ip50=r["ip_units"][s],
                        tg=cfg["tg_units"].get(s), ports=sorted(ports_per_site.get(s, [])),
                        agent=s in cfg["tg_units"] and s not in dead, traffic=s in endpoints,
                        fate="off at t0" if s in dead else f"island {r['comp'][s] + 1}"))
    return r, rows, mw, kit, counts(cfg, r)


def main():
    r, rows, mw, kit, c = plan()
    cfg = r["cfg"]
    sec_name = ["E", "N", "W", "S"]
    L = ["# Option A build plan (generated by option_a_plan.py)", "",
         f"60 GHz model: MARL paper Table III at {P_PLAN} dBm. Conducted loss reproducing a path = "
         f"FSPL + O2 − {ANT_GAIN_TOTAL:.0f} dB. Chain per path: {VPAD_DB:.0f} dB pad and splitter at each "
         f"sector port, {JUMPER_DB:.0f} dB jumpers, one programmable attenuator. Off-beam = on-beam + "
         f"{2 * SIDELOBE_PER_END:.0f} dB (15 dB sidelobe per end). Cut = {ATT_MAX:.0f} dB.", "",
         "## Site carts", "",
         "| Site | Role | IP-50 | TG | Used sector ports (fan-out) | Agent PC | Traffic host | Router + PDU | After t0 |",
         "|---|---|---|---|---|---|---|---|---|"]
    for k in kit:
        tg = {"DN": "node (DN)", "CN": "terminal (CN)"}.get(k["tg"], "–")
        ports = (", ".join(f"{sec_name[s]}×{n}" for s, n in k["ports"]) if k["tg"] == "DN"
                 else f"single port ×{k['ports'][0][1]}" if k["ports"] else "–")
        L.append(f"| {k['site']} | {k['role']} | {k['ip50'] or '–'} | {tg} | {ports} | "
                 f"{'yes' if k['agent'] else '–'} | {'yes' if k['traffic'] else '–'} | yes | {k['fate']} |")
    L += ["", "## V-band RF mesh: attenuator settings (dB)", "",
          "| Path | Role | Distance | Air-equivalent loss | Splitters | On-beam | Before event | At t0 | After recovery |",
          "|---|---|---|---|---|---|---|---|---|"]
    for x in rows:
        L.append(f"| {x['a']}–{x['b']} | {x['role']} | {x['d']:.0f} m | {x['target']:.1f} | "
                 f"{x['split_a']:.1f} + {x['split_b']:.1f} | {x['on']:.1f} | {x['before']:.1f} | "
                 f"{x['at_t0']:.1f} | {x['after']:.1f} |")
    ons = [x["on"] for x in rows]
    offs = [x["off"] for x in rows]
    L += ["", f"Attenuator range used: {min(ons):.1f} dB (on-beam, shortest) to {max(offs):.1f} dB (off-beam, "
          f"longest), plus {ATT_MAX:.0f} dB to cut. A 0–95 dB part covers it.", "",
          "## Microwave chains", "",
          "| Hop | Fixed pads | Programmable attenuator at rest | At t0 |", "|---|---|---|---|"]
    for m in mw:
        L.append(f"| {m['a']}–{m['b']} | {m['pads']:.0f} dB (2 × {MW_PAD_DB:.0f}) | {m['att']:.0f} dB + fades | "
                 f"{'95 dB (cut)' if m['cut'] else 'unchanged'} |")
    L += ["", "Set each microwave chain so the received level sits at the IP-50's nominal operating point "
          "(check the datasheet for the band); the programmable attenuator then adds fades for DPIR and "
          "cuts the core spokes at t0.", "",
          f"Totals: {c['n_ip']} IP-50, {c['n_dn']} TG nodes + {c['n_cn']} TG terminals, {c['tg_paths']} V-band "
          f"paths, {c['splitters']} splitters, {c['tg_ports']} V-band ports."]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "option_A_plan.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
