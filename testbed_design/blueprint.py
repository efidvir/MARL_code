    def box(self, x, y, w, h, title, sub=None, lw=0.9, fs=6.6, dashed=False, fill=None):
        self.ax.add_patch(Rectangle((x, y), w, h, fill=fill is not None, fc=fill or PAPER, ec=INK, lw=lw,
                                    ls=(0, (3, 2)) if dashed else "-", zorder=3))
