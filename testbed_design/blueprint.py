BOX_KIND = {"GTS003": (2, 2), "GTST002B": (1, 4), "GTST003": (2, 2)}   # nodes per box, sectors per node


class Bench:
    """design keys: boxes [dict(id, code, kind, u, nodes)], nodes {site: dict(box, slot, sectors, pol)},
    module {(site, sector): (box, 'M<k>')}, sector_of(site, peer) -> sector letter,
    tg_links {name: (a, b)}, mw_links {name: (a, b)}, couplings {name: ((site, sec), (site, sec))},
    hosts {host: [sites]}, single_tile (bool)."""

    def __init__(self, d):
        self.d = d
        self.tiles = 1 if d.get("single_tile") else 4
        self.cables = []
        self.n = {}
        self._build()

    def cid(self, cls):
        self.n[cls] = self.n.get(cls, 0) + 1
        prefix = {"AC": "A", "DC": "D", "POE": "P", "FIB": "F", "ETH": "E", "RF": "R", "GNSS": "G", "WG": "W"}[cls]
        return f"{prefix}{self.n[cls]:03d}"

    def add(self, cls, a, b, part, length, note=""):
        c = dict(id=self.cid(cls), cls=cls, a=a, b=b, part=part, length=length, note=note)
        self.cables.append(c)
        return c

    def _build(self):
        d = self.d
        self.coupled = {}            # (site, sector) -> coupler id
        for k, (x, y) in d["couplings"].items():
            for s in (x, y):
                self.coupled.setdefault(s, f"CPL-{s[0]}{s[1]}")
        self.atts = OrderedDict()    # unit -> what it carries
        for name in d["tg_links"]:
            self.atts[f"ATT-{len(self.atts) + 1:02d}"] = ("link", name)
        for name in d["couplings"]:
            self.atts[f"ATT-{len(self.atts) + 1:02d}"] = ("arm", name)
        self.att_of = {v[1]: k for k, v in self.atts.items()}
        nodes = list(d["nodes"])
        self.adaptor = {n: f"PA-{i + 1:02d}" for i, n in enumerate(nodes)}
        self.n_adaptors = max(10, len(nodes))
        mw = d.get("mw_links", {})
        self.ip50 = OrderedDict()
        for k, (a, b) in mw.items():
            self.ip50[f"IP50-{k}-{a}"] = (k, a)
            self.ip50[f"IP50-{k}-{b}"] = (k, b)
        # AC ------------------------------------------------------------------------------
        self.add("AC", "Lab wall socket IEC 60309 32 A", "PDU.inlet", "PDU cord (IEC 60309 32 A plug)", "fixed")
        loads = ["DC-RECT.inlet", "SW-DATA.psu", "SW-OOB.psu", "GNSS-SPL.inlet"] + [f"{a}.ac" for a in self.atts]
        self.pdu_map = OrderedDict()
        for i, ld in enumerate(loads):
            self.pdu_map[ld] = f"PDU.O{i + 1}"
            self.add("AC", f"PDU.O{i + 1}", ld, "Eaton Tripp Lite P004-006 (C14-C13, 1.8 m) or PXT1001M (1 m)", "1 m")
        for t in ["SRV-DPIR", "SRV-E2E", "SPECAN"] + [f"HOST-{h}" for h in d["hosts"]]:
            plug = "C5 'Mickey' lead P014-006" if t.startswith("HOST") else "C14-C13 lead P004-006"
            self.add("AC", "Bench power strip (table)", f"{t}.ac", plug, "1.8 m")
        # DC --------------------------------------------------------------------------------
        self.add("DC", "DC-RECT.bus+", "DC-DIST.bus+", "Shelf busbar link (2 x 10 AWG, lugs)", "0.3 m", "48 V bus")
        for i in range(self.n_adaptors):
            node = nodes[i] if i < len(nodes) else None
            self.add("DC", f"DC-DIST.CB{i + 1}", f"PA-{i + 1:02d}.dc",
                     "Belden 8461 2 x 18 AWG + Phoenix AI 0,75-8 ferrules", "1 m",
                     f"feeds {node}" if node else "spare adaptor (not connected to a node)")
        for k, (kk, site) in self.ip50.items():
            self.add("DC", "DC-RECT2.-48V", f"{k}.dc", "Belden 8461 2 x 18 AWG (IP-50 -48 V; connector TBC)", "3 m",
                     "-48 V, separate rectifier group (positive grounded)")
        # PoE (power only) -------------------------------------------------------------------
        for n in nodes:
            b = d["nodes"][n]["box"]
            self.add("POE", f"{self.adaptor[n]}.rj45", f"{b}.{n}.ETH1", "Panduit STP6X1MBU Cat6A S/FTP 1 m", "1 m",
                     "power only (passive DC/PoE adaptor)")
        # data: fibre / DAC ------------------------------------------------------------------
        self.sw_port = OrderedDict()
        p = 1
        for n in nodes:
            b = d["nodes"][n]["box"]
            self.sw_port[f"{b}.{n}.SFP+"] = (p, f"VLAN {self.vlan(n)}")
            self.add("FIB", f"{b}.{n}.SFP+", f"SW-DATA.P{p}",
                     "2 x 10G SR SFP+ (Siklu AX-SFP+10G-MM at node, Netgear AXM761 at switch) + Panduit FZ2ERLNLNSNM002 OM4 2 m",
                     "2 m", f"site {n}, access port VLAN {self.vlan(n)}")
            p += 1
        for k, (kk, site) in self.ip50.items():
            self.sw_port[f"{k}.data"] = (p, f"VLAN {self.vlan(site)}")
            self.add("FIB", f"{k}.data", f"SW-DATA.P{p}", "Cat6A / SFP+ per IP-50 data port (TBC)", "3 m",
                     f"IP-50 hop {kk}, site {site}, VLAN {self.vlan(site)}")
            p += 1
        for h, sites in d["hosts"].items():
            self.sw_port[f"HOST-{h}.nic10g"] = (p, "trunk " + ", ".join(str(self.vlan(s)) for s in sites))
            self.add("FIB", f"HOST-{h}.nic10g", f"SW-DATA.P{p}", "Netgear AXC763-10000S SFP+ DAC 3 m", "3 m",
                     "tagged: " + ", ".join(f"VLAN {self.vlan(s)} ({s})" for s in sites))
            p += 1
        # management / control ----------------------------------------------------------------
        q = 1
        self.oob_port = OrderedDict()

        def oob(src, part="Panduit STP6X1MBU Cat6A 1-2 m", note="management VLAN 100"):
            nonlocal q
            self.oob_port[src] = q
            self.add("ETH", src, f"SW-OOB.P{q}", part, "2 m", note)
            q += 1
        for n in nodes:
            oob(f"{d['nodes'][n]['box']}.{n}.ETH2", note="node management (PoE-Out on ETH2 disabled)")
        for a in self.atts:
            oob(f"{a}.lan", note="attenuator control (10BASE-T, SCPI over TCP)")
        for k in self.ip50:
            oob(f"{k}.mgmt", note="IP-50 management (port TBC)")
        oob("PDU.net", note="PDU management")
        for t in ["SRV-DPIR", "SRV-E2E", "SPECAN"] + [f"HOST-{h}" for h in d["hosts"]]:
            oob(f"{t}.mgmt")
        # GNSS -------------------------------------------------------------------------------
        self.add("GNSS", "GNSS antenna (roof) Protempis 101898-00", "GNSS-SPL.in",
                 "LMR-400 coax + surge arrestor, TNC/N (length per site)", "site")
        for i, b in enumerate(d["boxes"]):
            self.add("GNSS", f"GNSS-SPL.out{i + 1}", f"{b['id']}.GNSS", "LMR-195 / RG-316 SMA coax", "1 m",
                     "only if the box has a GNSS input (TBC); else GPS-less / RF sync")
        # RF / IF ------------------------------------------------------------------------------
        T = range(1, self.tiles + 1)
        for name, (a, b) in d["tg_links"].items():          # one bundle of 4 at a time: consecutive IDs
            att = self.att_of[name]
            sa, sb = (a, d["sector_of"](a, b)), (b, d["sector_of"](b, a))
            for side, s in (("in", sa), ("out", sb)):
                box, mod = d["module"][s]
                if s in self.coupled:
                    for t in T:
                        self.add("RF", f"{box}.{mod}.T{t}", f"{self.coupled[s]}.t{t}.IN",
                                 "Mini-Circuits 086-4SM+ (SMA-M/M, 18 GHz)", "0.1 m",
                                 f"{name} {s[0]}.{s[1]} tile {t}: coupler IN on the module side")
                    for t in T:
                        self.add("RF", f"{self.coupled[s]}.t{t}.THRU", f"{att}.ch{t}.{side}",
                                 "Mini-Circuits CBL-2FT-SMSM+", "0.6 m", f"{name} tile {t}")
                else:
                    for t in T:
                        self.add("RF", f"{box}.{mod}.T{t}", f"{att}.ch{t}.{side}", "Mini-Circuits CBL-2FT-SMSM+",
                                 "0.6 m", f"{name} {s[0]}.{s[1]} tile {t}")
        for name, (x, y) in d["couplings"].items():
            att = self.att_of[name]
            for t in T:
                self.add("RF", f"{self.coupled[x]}.t{t}.CPL", f"{att}.ch{t}.in",
                         "BLK-18-S+ DC block + BW-S<n>W2+ pad at the coupler, then CBL-2FT-SMSM+", "0.6 m",
                         f"arm {name} tile {t} (phase-matched lengths across the 4 tiles)")
            for t in T:
                self.add("RF", f"{att}.ch{t}.out", f"{self.coupled[y]}.t{t}.CPL", "Mini-Circuits CBL-2FT-SMSM+",
                         "0.6 m", f"arm {name} tile {t}")
        # IP-50 conducted chains ------------------------------------------------------------------
        for k, (a, b) in mw.items():
            ra, rb = f"IP50-{k}-{a}", f"IP50-{k}-{b}"
            self.add("WG", f"{ra}.wg", f"WGT-{k}-{a}", "waveguide-to-coax transition (band TBC: PEWCA1003 / PEWCA1018)",
                     "flange", f"hop {k}")
            self.add("WG", f"WGT-{k}-{a}", f"MWATT.{k}.in", "30 dB 10 W pad (SA18S10W-30) + coax", "1 m", f"hop {k}")
            self.add("WG", f"MWATT.{k}.out", f"WGT-{k}-{b}", "30 dB 10 W pad (SA18S10W-30) + coax", "1 m", f"hop {k}")
            self.add("WG", f"WGT-{k}-{b}", f"{rb}.wg", "waveguide-to-coax transition (band TBC)", "flange", f"hop {k}")

    def vlan(self, site):
        return 101 + list(self.d["nodes"]).index(site)

    def count(self, cls, part_sub=None):
        return sum(1 for c in self.cables if c["cls"] == cls and (part_sub is None or part_sub in c["part"]))


