def ids_between(b, a_prefix, b_prefix):
    cs = [c["id"] for c in b.cables if c["cls"] == "RF" and c["a"].startswith(a_prefix) and c["b"].startswith(b_prefix)]
    nums = [int(c[1:]) for c in cs]
    assert len(cs) == b.tiles and nums == list(range(nums[0], nums[0] + len(nums))), (a_prefix, b_prefix, cs)
    return f"{cs[0]}-{cs[-1][1:]}" if len(cs) > 1 else cs[0]


