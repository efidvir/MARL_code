def draw_boxes(s, b, x, ytop, w, row_h, port_side="r", ports=("ETH1",), gnss=False):
    """Spider boxes as frames holding node blocks; returns {(node, port): (x, y)} and box GNSS port positions."""
    pos, gpos = {}, {}
    y = ytop
    for x_ in b.d["boxes"]:
        nn = len(x_["nodes"])
        hbox = nn * row_h + 7
        s.ax.add_patch(Rectangle((x, y - hbox), w, hbox, fc="#1d4f8c", ec=INK, lw=0.9, zorder=2))
        s.text(x + 1.5, y - 2.6, f"{x_['id']}  {x_['code']}", fs=5.4, fontweight="bold", va="center")
        yy = y - 6
        for nd in x_["nodes"]:
            info = b.d["nodes"][nd]
            s.ax.add_patch(Rectangle((x + 2, yy - row_h + 1), w - 4, row_h - 1.5, fc=PAPER, ec=INK, lw=0.6, zorder=3))
            tx = x + (10 if port_side == "l" else 3.5)
            s.text(tx, yy - row_h / 2 + 0.3, f"node {nd}", fs=5.2, va="center", fontweight="bold")
            s.text(tx, yy - row_h / 2 - 2.4, f"{info['sectors']}-sector · {info['pol']}", fs=4.0, color=DIM,
                   va="center")
            for i, p in enumerate(ports):
                py = yy - 1.8 - i * (row_h - 3) / max(1, len(ports) - 1) if len(ports) > 1 else yy - row_h / 2
                px = x + w - 2 if port_side == "r" else x + 2
                s.port(px, py, p, side=port_side)
                pos[(nd, p)] = (px, py)
            yy -= row_h
        if gnss:
            gx, gy = x + w, y - 3
            s.port(gx, gy, "GNSS", side="r")
            gpos[x_["id"]] = (gx, gy)
        y -= hbox + 3
    return pos, gpos, y


