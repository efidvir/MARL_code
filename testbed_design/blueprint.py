def rack_layout(b):
    d = b.d
    top = [("GNSS-SPL", 1, "GNSS splitter 1x8", "RMALDCBS1X8 (if the boxes take GNSS)"),
           ("SW-DATA", 1, "Data switch", "Netgear M4350-24F4V"),
           ("SW-OOB", 1, "Management switch", "Netgear M4250-26G4XF-PoE+"),
           ("CM", 1, "Cable manager", "Panduit NCMHF1")]
    boxes = [(x["id"], 1, f"{x['code']}  ·  " + ", ".join(x["nodes"]),
              f"{x['kind']} · " + "/".join(sorted({d['nodes'][n]['pol'] for n in x['nodes']}))) for x in d["boxes"]]
    mid = [("CPL-TRAY", 1, "Coupler tray (shelf)", f"{len(b.coupled) * b.tiles} couplers, DC blocks, pads")] if b.coupled else []
    atts = [(a, 1, f"{a}  ·  " + ("link " if v[0] == "link" else "arm ") + v[1], "ZTDAT-4-18G63S")
            for a, v in b.atts.items()]
    low = [("PA-SHELF", 1, "DC/PoE adaptors PA-01..PA-10", "Siklu EH-PoE-DC-Adaptor x 10 on a shelf"),
           ("DC-DIST", 1, "DC distribution 48 V, 10 breakers", "Eaton DCD1M"),
           ("DC-RECT", 1, "DC rectifier shelf 48 V", "Mean Well RCP-1UI + 2 x RCP-1000-48")]
    if b.ip50:
        low.append(("DC-RECT2", 1, "-48 V rectifier (IP-50)", "RCP-1UI + RCP-1000-48"))
    low.append(("PDU", 2, "PDU 32 A, 16 x C13", "APC AP7922B"))
    units = top + boxes + mid + atts + low
    total = sum(u[1] for u in units)
    size = 25 if total <= 25 else 42
    rows, u = [], size
    for k, n, lab, sub in units:
        rows.append(dict(id=k, top=u, n=n, label=lab, sub=sub))
        u -= n
    return size, rows, total


