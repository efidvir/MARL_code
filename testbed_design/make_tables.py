"""Write out/tables.md: per-configuration equipment, DPIR candidates, islands,
MARL bridge candidates and the TG polarity plan, all taken from
validate.analyze()."""
import os

from topologies import CONFIGS
from validate import P_PLAN, analyze

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")
SECTOR = ["east", "north", "west", "south"]


def main():
    lines = ["# Testbed tables (generated by make_tables.py from validate.py)", "",
             f"60 GHz budgets: MARL paper Table III model at the {P_PLAN} dBm planning power; "
             "margin = SNR above the QPSK-1/3 threshold (-3 dB). Distances are schematic.", ""]
    for key in CONFIGS:
        r = analyze(key)
        cfg = r["cfg"]
        lines += [f"## Configuration {cfg['name']}", ""]
        lines += ["| Site | Role | IP-50 units | TG unit | After the event |", "|---|---|---|---|---|"]
        for s in cfg["sites"]:
            tg = {"DN": "node-class (DN)", "CN": "terminal-class (CN)"}.get(cfg["tg_units"].get(s), "-")
            fate = "destroyed" if s in cfg["destroyed"] else f"island {r['comp'][s] + 1}"
            from topologies import ROLE
            lines.append(f"| {s} | {ROLE[s].splitlines()[0]} | {r['ip_units'][s] or '-'} | {tg} | {fate} |")
        lines += ["", f"Totals: {sum(r['ip_units'].values())} IP-50 ({len(cfg['mw'])} fixed PtP links), "
                  f"{len(cfg['tg_units'])} TG. Lost in the event: {r['lost_ip']} IP-50, {r['lost_tg']} TG.", ""]
        lines += ["**DPIR flows and candidate paths (before the event)**", "",
                  "| Flow | Candidate | Path | Links |", "|---|---|---|---|"]
        for fid, s, t in cfg["flows"]:
            for j, p in enumerate(r["dpir"][fid]):
                lines.append(f"| {fid} {s}→{t} | {'ab'[j]} | {'–'.join(p)} | "
                             f"{' + '.join(r['path_tech'](p))} |")
        if r["shared"]:
            lines += ["", "Shared TG sectors (the flows' TG candidates contend for this airtime): "
                      + "; ".join(f"{site} {SECTOR[sec]} sector serves {', '.join(y for _, y in v)}"
                                  for (site, sec), v in r["shared"].items())]
        for (s, t), p in r["service"].items():
            lines.append(f"\nService flow {s}→{t} (single-homed pocket, MARL only): {'–'.join(p)}")
        if cfg.get("tg_fixed"):
            lines.append("\nFixed links on a spare sector of installed TG nodes (no extra radio): "
                         + ", ".join(f"{a}–{b}" for a, b in cfg["tg_fixed"]))
        lines += ["", "**Islands after the event**: " + "; ".join(
            f"{i + 1}: {', '.join(isl)}" for i, isl in enumerate(r["islands"])), ""]
        lines += ["**Bridge candidates**", "",
                  "| Pair | Distance | MCS | Margin | Feasible | Chosen |", "|---|---|---|---|---|---|"]
        chosen = {frozenset(b): (i + 1, b) for i, b in enumerate(cfg["bridges"])}
        for c in r["cands"]:
            b = c["budget"]
            f = "yes" if c["feasible"] else "no: " + "; ".join(c["why"])
            ch = chosen.get(frozenset((c["a"], c["b"])))
            lines.append(f"| {c['a']}–{c['b']} | {c['d']:.0f} m | {b['mcs'] or 'no link'} | "
                         f"{b['margin']:.1f} dB | {f} | "
                         f"{f'bridge {ch[0]} ({ch[1][0]} ignites)' if ch else ''} |")
        lines += ["", "**Beam changes** (the node-class end ignites the bridge)", ""]
        for st in r["steer"]:
            where = SECTOR[st["sector"]] + " sector" if cfg["tg_units"][st["unit"]] == "DN" else "its sector"
            if st["old"]:
                lines.append(f"- {st['unit']} ({st['role']}): {where} beam that served {st['old']} turns "
                             f"{st['delta']:.0f}° to {st['new']}")
            else:
                lines.append(f"- {st['unit']} ({st['role']}): {where} ({st['change']}) points at {st['new']}")
        lines += ["", "**TG polarity plan** (set before the event; hybrid per sector): "
                  + ", ".join(f"{s} {SECTOR[sec] if cfg['tg_units'][s] == 'DN' else 'sector'} = {v}"
                              for (s, sec), v in sorted(r["polarity"].items())), ""]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "tables.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.join(OUT, "tables.md"))


if __name__ == "__main__":
    main()
