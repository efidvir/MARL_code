"""Write out/tables.md: per-configuration equipment, DPIR paths, islands and
MARL bridge candidates, all taken from validate.analyze()."""
import os

from topologies import CONFIGS
from validate import P_BOOST, P_PLAN, analyze

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")


def techs(t):
    return " + ".join(t)


def main():
    lines = ["# Testbed tables (generated by make_tables.py)", ""]
    for key in CONFIGS:
        r = analyze(key)
        cfg = r["cfg"]
        lines += [f"## Configuration {cfg['name']}", ""]
        lines += ["| Site | IP-50 units | TG unit | Fate |", "|---|---|---|---|"]
        for s in cfg["sites"]:
            tg = {"DN": "node-class (DN)", "CN": "terminal-class (CN)"}.get(cfg["tg_units"].get(s), "-")
            fate = "destroyed" if s in cfg["destroyed"] else "survives"
            lines.append(f"| {s} | {r['ip_units'][s] or '-'} | {tg} | {fate} |")
        lines += ["", f"Totals: {sum(r['ip_units'].values())} IP-50, {len(cfg['tg_units'])} TG. "
                  f"Lost in the event: {r['lost_ip']} IP-50, {r['lost_tg']} TG.", ""]
        lines += ["**DPIR flows and candidate paths (before the event)**", "",
                  "| Flow | Candidate | Path | Links |", "|---|---|---|---|"]
        for fid, s, t in cfg["flows"]:
            for j, p in enumerate(r["dpir"][fid]):
                lines.append(f"| {fid} {s}→{t} | {'abc'[j]} | {'–'.join(p)} | {techs(r['path_tech'](p))} |")
        lines += ["", "**Islands after the event**: " + "; ".join(
            f"{i + 1}: {', '.join(isl)}" for i, isl in enumerate(r["islands"])), ""]
        lines += ["**Bridge candidates (60 GHz, MARL paper Table III model)**", "",
                  f"| Pair | Distance | @{P_PLAN} dBm | @{P_BOOST} dBm | Feasible | Chosen |",
                  "|---|---|---|---|---|---|"]
        chosen = {frozenset(b): i + 1 for i, b in enumerate(cfg["bridges"])}
        for c in r["cands"]:
            b = c["budget"]
            f = "yes" if c["feasible"] else "no: " + "; ".join(c["why"])
            ch = chosen.get(frozenset((c["a"], c["b"])))
            lines.append(f"| {c['a']}–{c['b']} | {c['d']:.0f} m | {b[P_PLAN]['mcs'] or 'no link'} "
                         f"({b[P_PLAN]['snr']:.1f} dB) | {b[P_BOOST]['mcs'] or 'no link'} "
                         f"({b[P_BOOST]['snr']:.1f} dB) | {f} | {('bridge ' + str(ch)) if ch else ''} |")
        lines += ["", "**Beam changes**", ""]
        for st in r["steer"]:
            if st["kind"] == "re-steer":
                lines.append(f"- {st['unit']} ({st['role']}): beam that served {st['old']} swings "
                             f"{st['delta']:.0f}° to {st['new']}")
            else:
                lines.append(f"- {st['unit']} ({st['role']}): a free sector of the node takes {st['new']}")
        lines.append("")
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "tables.md"), "w") as fh:
        fh.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
