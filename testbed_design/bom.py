"""Bill of materials for the physical testbed, per configuration.

Quantities are derived from the topology spec (topologies.py) so they stay
in step with the figures.  Run:  python3 bom.py   -> out/hardware.md
"""
import os

from topologies import CONFIGS

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")


def counts(cfg):
    n_sites = len(cfg["sites"])
    n_mw = len(cfg["mw"])
    n_ip = 2 * n_mw
    n_dn = sum(1 for v in cfg["tg_units"].values() if v == "DN")
    n_cn = sum(1 for v in cfg["tg_units"].values() if v == "CN")
    n_tg = n_dn + n_cn
    agents = sum(1 for s in cfg["tg_units"] if s not in cfg["destroyed"])
    endpoints = len({x for _, a, b in cfg["flows"] for x in (a, b)}
                    | {x for a, b in cfg.get("service", []) for x in (a, b)})
    return dict(n_sites=n_sites, n_mw=n_mw, n_ip=n_ip, n_dn=n_dn, n_cn=n_cn, n_tg=n_tg,
                agents=agents, endpoints=endpoints)


# (group, item, quantity rule, note)
ITEMS = [
    ("Radios", "Ceragon IP-50 radio unit (e.g. IP-50C)", lambda c: c["n_ip"],
     "one per microwave link end"),
    ("Radios", "Siklu MultiHaul TG node, 4 x 90 deg (N366/N367 class)", lambda c: c["n_dn"],
     "hub, core spur and every steerable west/east site"),
    ("Radios", "Siklu MultiHaul TG terminal (T265 class)", lambda c: c["n_cn"],
     "shelter / field-hospital pockets"),
    ("RF path", "Waveguide-to-coax transition, IP-50 band", lambda c: c["n_ip"],
     "lab: microwave runs conducted, in place of the dish"),
    ("RF path", "Fixed attenuator pad, ~30 dB, band-rated", lambda c: 2 * c["n_mw"],
     "two per link: protects receivers, sets the nominal hop loss"),
    ("RF path", "Programmable step attenuator, 0-95 dB, USB/LAN", lambda c: c["n_mw"],
     "one per microwave link: fades for DPIR, cut at the event"),
    ("RF path", "Low-loss coax jumper, band-rated", lambda c: 2 * c["n_mw"], ""),
    ("RF path", "60 GHz absorber / attenuating screen set", lambda c: c["n_tg"],
     "TG arrays have no RF port: set path loss over the air, kill reflections"),
    ("RF path", "TG pole or tripod mount + alignment bracket", lambda c: c["n_tg"], ""),
    ("Power", "Switched, metered PDU (per-outlet, network-controlled)", lambda c: c["n_sites"],
     "switches CORE and HUB off at t0; measures energy per site"),
    ("Power", "PoE injector for TG unit (rating per datasheet)", lambda c: c["n_tg"], ""),
    ("Power", "-48 VDC supply + distribution for IP-50", lambda c: 1, "lab bench supply"),
    ("Network", "Site router / L3 switch, per-flow policy routing, SFP+", lambda c: c["n_sites"],
     "pins DPIR paths (VLAN or SR steering)"),
    ("Compute", "Edge agent PC per surviving TG site", lambda c: c["agents"],
     "frozen MARL actor, local TG control, heartbeats, logs"),
    ("Compute", "Traffic generator / sink host (iperf3, TRex)", lambda c: c["endpoints"],
     "at every flow and service endpoint"),
    ("Compute", "Servers: DPIR controller + predictor (GPU); TG E2E controller + NMS", lambda c: 2,
     "the TG controller sits at CORE and is lost with it"),
    ("Network", "Out-of-band switch (logging only) + PTP/GNSS time server", lambda c: 2,
     "logs and clock; never a control path during the event"),
    ("Cabling", "SFP+ 10G modules / LC fibre patch cords", lambda c: f"{2 * c['n_tg']} / {c['n_tg']}",
     "TG uplinks"),
    ("Cabling", "Cat6A cables (PoE + data), approx.",
     lambda c: c["n_ip"] + c["n_tg"] + 2 * c["agents"] + c["endpoints"] + c["n_sites"], ""),
    ("Test", "Microwave + V-band power meters (calibration)", lambda c: 1, "one set"),
]


def table():
    keys = list(CONFIGS)
    cs = {k: counts(CONFIGS[k]) for k in keys}
    rows = []
    for group, item, rule, note in ITEMS:
        rows.append((group, item, [rule(cs[k]) for k in keys], note))
    return keys, cs, rows


def main():
    keys, cs, rows = table()
    head = "| Group | Item | " + " | ".join(f"{k} ({CONFIGS[k]['ip50']}+{CONFIGS[k]['tg']})" for k in keys) + " | Note |"
    lines = ["# Testbed hardware (generated by bom.py)", "",
             "Quantities follow the topology spec; `n` per configuration.", "", head,
             "|" + "---|" * (len(keys) + 3)]
    for group, item, q, note in rows:
        lines.append(f"| {group} | {item} | " + " | ".join(str(x) for x in q) + f" | {note} |")
    lines += ["", "Assumptions: indoor lab; microwave conducted through attenuators; 60 GHz over the air with",
              "absorber screens (or outdoors at real distances); the event = PDU outlets of CORE and HUB",
              "switched off at t0 plus the core-spoke attenuators driven to maximum. Confirm power, PoE",
              "class, SFP and mounting details against the Ceragon and Siklu datasheets."]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "hardware.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
